@Configuration
    
public class BatchConfiguration {
    
    
    @Autowired
    CFStepHandler cfStepHandler;
    
    @Autowired
    ApplicationContext context;
    
    private static final String JOBNAME = "Y91DEXT2";
    
    /* Driver Programs used in steps */  
   private static final String SORT = "SORT";
    
    private static final String COMPLETED_STATUS = "COMPLETED";
    private static final String CONTINUE_STATUS = "CONTINUE";
    
    /** 
     *   Execute the Job that consists of 
     * S030_P080 - SORT
     * 
     * @param jobRepository 
     * @param transactionManager 
     * @return 
     */ 
    @Bean 
    public Job job(JobRepository jobRepository, PlatformTransactionManager transactionManager) {
      GlobalExecutorCtx.load(BatchConfiguration.class, context);
	    return new JobBuilder(JOBNAME, jobRepository)
			.start(s030_p080Executor(jobRepository, transactionManager)) /*  */
		.next(printSummary(jobRepository, transactionManager)) 
		.end() 

    			.build();
    } 
    /*
     * S030_P080 SORT starts here
     */
    
    private static final String S030_P080_STEP = "s030_p080";
    @Bean
    @JobScope
    public Y91dext2S030_p080Sort y91dext2S030_p080Sort() {
    	return new Y91dext2S030_p080Sort();
    }
    
    @Bean
    @JobScope
    protected Step Y91dext2S030_p080Sort(JobRepository jobRepository, PlatformTransactionManager transactionManager) {
    	return new StepBuilder("Y91dext2S030_p080Sort",jobRepository).tasklet(y91dext2S030_p080Sort(), transactionManager).build();  
    }
    
    @Bean
    public Step s030_p080Decider(JobRepository jobRepository, PlatformTransactionManager transactionManager) {
        return new StepBuilder("s030_p080Decider",jobRepository).tasklet(new Tasklet() {
    
 	      @Override
 	      public RepeatStatus execute(StepContribution contribution, ChunkContext chunkContext) throws Exception {
 	          int rc = 0;
            String stepStatus = COMPLETED_STATUS;
                if (cfStepHandler.stepDecider(S030_P080_STEP)) { 
                     try {
 		    	   			cfStepHandler.handleStepOverrides(S030_P080_STEP);
                     } catch (CFException e) {
                         rc = 12;
                         cfStepHandler.setAbendCode(e);
                         stepStatus = CONTINUE_STATUS;
                     }
                }
            	  else { stepStatus = CONTINUE_STATUS; }
 		    	  cfStepHandler.postStepExecution(S030_P080_STEP, rc, SORT );
    		      cfStepHandler.updateStepExecution(S030_P080_STEP, chunkContext , rc+"" , stepStatus);
 		      return RepeatStatus.FINISHED;
 		  } 
 	    }, transactionManager).build();
 	  }
    
  /*  
     * Member Info:
     *  SORT FIELDS=COPY                                                               
     *  OUTREC OVERLAY=(1:1,123,1X,&DATE1-5)                                           
     */
    @Bean
    public Flow s030_p080Executor(JobRepository jobRepository, PlatformTransactionManager transactionManager) {
       return new FlowBuilder<SimpleFlow>("s030_p080Executor")
             .start(s030_p080Decider(jobRepository, transactionManager))
             .from(s030_p080Decider(jobRepository, transactionManager)).on(COMPLETED_STATUS)
             .to(Y91dext2S030_p080Sort(jobRepository, transactionManager))
             .from(s030_p080Decider(jobRepository, transactionManager)).on("*").end()
 	           .build();
    }
    /*
     * S030_P080 SORT Ends here 
     */
    
	
	@Bean
	public Step printSummary(JobRepository jobRepository, PlatformTransactionManager transactionManager) {
    return new StepBuilder("printSummary", jobRepository).tasklet(new Tasklet() {
	    @Override
	    public RepeatStatus execute(StepContribution contribution, ChunkContext chunkContext) throws Exception {
          cfStepHandler.printExecutionSummary();
          return RepeatStatus.FINISHED;
      }
	  }, transactionManager).build();
	}
	    
}
